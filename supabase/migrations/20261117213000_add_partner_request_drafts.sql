create table if not exists public.partner_request_drafts (
  id bigint generated by default as identity primary key,
  partner_id bigint not null references public.partners(id) on delete cascade,
  created_by uuid not null references auth.users(id) on delete cascade,
  payload jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists partner_request_drafts_partner_updated_idx
  on public.partner_request_drafts(partner_id, updated_at desc);

alter table public.partner_request_drafts enable row level security;
revoke all on table public.partner_request_drafts from anon, authenticated;
